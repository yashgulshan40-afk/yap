#!/usr/bin/env python3
"""
YAP Portfolio Builder
---------------------
Apni photos / videos ko category folders me daalo:

    assets/portfolio/social-media/brew-and-co-launch.jpg
    assets/portfolio/reels/fitzone-transformation.mp4
    assets/portfolio/branding/aura-logo.png

Phir chalao:

    python3 tools/portfolio_builder.py

Yeh assets/js/portfolio-data.js bana dega aur website par portfolio
apne aap update ho jayega. File ka naam hi project ka title banta hai
("brew-and-co-launch.jpg" -> "Brew And Co Launch").

Extra details (client, description, tags, video link) ke liye
image ke saath same naam ki .json file rakho:

    assets/portfolio/reels/fitzone-transformation.json
    {
      "title": "FitZone 30-day transformation",
      "client": "FitZone Gym",
      "desc": "1.2M views, 3,400 new followers in 30 days.",
      "tags": ["Reels", "Editing"],
      "video": "https://www.instagram.com/reel/xxxx",
      "link": ""
    }

Sirf Python 3 chahiye, koi extra library nahi.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "portfolio"
OUT = ROOT / "assets" / "js" / "portfolio-data.js"
MEDIA = {".jpg", ".jpeg", ".png", ".webp", ".gif", ".avif", ".mp4", ".webm", ".mov"}

# folder name -> category label shown on the site
LABELS = {
    "social-media": "Social Media",
    "reels": "Reels",
    "branding": "Branding",
    "design": "Design",
    "websites": "Websites",
    "ads": "Ads",
}


def nice(name: str) -> str:
    return " ".join(w.capitalize() for w in name.replace("_", "-").split("-") if w)


def main() -> int:
    if not SRC.is_dir():
        print(f"Folder nahi mila: {SRC}")
        return 1

    items = []
    for folder in sorted(p for p in SRC.iterdir() if p.is_dir()):
        category = LABELS.get(folder.name, nice(folder.name))
        files = sorted(f for f in folder.iterdir() if f.suffix.lower() in MEDIA)
        # sabse naya kaam pehle
        files.sort(key=lambda f: f.stat().st_mtime, reverse=True)
        for f in files:
            item = {
                "title": nice(f.stem),
                "client": "",
                "category": category,
                "image": f.relative_to(ROOT).as_posix(),
                "desc": "",
                "tags": [category],
            }
            meta = f.with_suffix(".json")
            if meta.exists():
                try:
                    item.update(json.loads(meta.read_text(encoding="utf-8")))
                except json.JSONDecodeError as e:
                    print(f"  ! {meta.name} me JSON galat hai ({e}); skip kiya")
            items.append(item)
            print(f"  + [{category}] {item['title']}")

    body = json.dumps(items, ensure_ascii=False, indent=2)
    OUT.write_text(
        "/* Auto-generated by tools/portfolio_builder.py — do not edit by hand. */\n"
        f"window.YAP_PORTFOLIO = {body};\n",
        encoding="utf-8",
    )
    print(f"\n{len(items)} projects -> {OUT.relative_to(ROOT)}")
    if not items:
        print("Koi photo/video nahi mili, isliye website config.js wala sample portfolio dikhayegi.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
